-- Tool System V2 initial persistent job and evidence ledger.
-- ONLY apply to the new owner-approved Tool System V2 Supabase project.
-- Do not execute on the old money-agent-ai database.
begin;

create table if not exists public.money_ai_jobs (
  id text primary key,
  page text not null,
  source_url text not null,
  stage text not null default 'NEW'
    check (stage in ('NEW','SOURCE_READY','SCRIPT_READY','VIDEO_READY',
      'WAITING_APPROVAL','REVISION_REQUESTED','APPROVED','PUBLISHING',
      'PUBLISHED','BLOCKED')),
  source_path text,
  source_sha text,
  original_analysis text,
  script text,
  script_sha text,
  video_path text,
  video_sha text,
  duration double precision,
  frame_w integer,
  frame_h integer,
  owner_approved_sha text,
  schedule_at timestamptz,
  post_url text,
  error text,
  feedback text,
  provider text,
  hashtags text,
  review_message_id text,
  resume_stage text,
  publish_attempt text,
  updated_at timestamptz not null default now(),
  unique (page, source_url)
);

create index if not exists money_ai_jobs_stage_schedule_idx
  on public.money_ai_jobs(stage, schedule_at);

create table if not exists public.money_ai_events (
  id bigint generated by default as identity primary key,
  job_id text not null references public.money_ai_jobs(id) on delete restrict,
  kind text not null,
  details text not null,
  at timestamptz not null default now()
);

create index if not exists money_ai_events_job_idx
  on public.money_ai_events(job_id, id);

create table if not exists public.money_ai_lessons (
  id bigint generated by default as identity primary key,
  error_fingerprint text unique not null,
  cause text not null,
  tested_fix text not null,
  test_evidence text not null,
  created_at timestamptz not null default now()
);

-- No policy grants access to anonymous users or browser visitors.
alter table public.money_ai_jobs enable row level security;
alter table public.money_ai_events enable row level security;
alter table public.money_ai_lessons enable row level security;

revoke all on public.money_ai_jobs, public.money_ai_events,
  public.money_ai_lessons from anon, authenticated;
grant select, insert, update, delete on public.money_ai_jobs,
  public.money_ai_events, public.money_ai_lessons to service_role;
grant usage, select on sequence public.money_ai_events_id_seq,
  public.money_ai_lessons_id_seq to service_role;

commit;
